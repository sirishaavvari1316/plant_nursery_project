// ======================================================
// CHANGE LANGUAGE
// ======================================================

function changeLanguage(language) {

    localStorage.setItem(
        "selectedLanguage",
        language
    );

    applyLanguage(language);
}


// ======================================================
// APPLY LANGUAGE
// ======================================================

function applyLanguage(language) {

    // --------------------------------------
    // NORMAL TEXT
    // --------------------------------------

    const elements =
        document.querySelectorAll("[data-lang]");

    elements.forEach(function(element) {

        const key =
            element.getAttribute("data-lang");

        if (
            translations[key] &&
            translations[key][language]
        ) {

            element.innerText =
                translations[key][language];

        }

    });


    // --------------------------------------
    // PLACEHOLDERS
    // --------------------------------------

    const placeholderElements =
        document.querySelectorAll(
            "[data-lang-placeholder]"
        );

    placeholderElements.forEach(function(element) {

        const key =
            element.getAttribute(
                "data-lang-placeholder"
            );

        if (
            translations[key] &&
            translations[key][language]
        ) {

            element.placeholder =
                translations[key][language];

        }

    });


    // --------------------------------------
    // PLANT NAMES
    // --------------------------------------

    const plantNames =
        document.querySelectorAll(
            "[data-plant-name]"
        );

    plantNames.forEach(function(element) {

        const originalName =
            element.getAttribute(
                "data-plant-name"
            );

        const plantKey =
            getPlantTranslationKey(
                originalName
            );

        if (
            plantKey &&
            translations[plantKey] &&
            translations[plantKey][language]
        ) {

            element.innerText =
                translations[plantKey][language];

        }

    });


    // --------------------------------------
    // LANGUAGE SELECT BOX
    // --------------------------------------

    const languageSelect =
        document.getElementById(
            "languageSelect"
        );

    if (languageSelect) {

        languageSelect.value =
            language;

    }


    // --------------------------------------
    // HTML LANGUAGE
    // --------------------------------------

    document.documentElement.lang =
        language;


    // --------------------------------------
    // PAGE TITLE
    // --------------------------------------

    updatePageTitle(language);
}


